/**
 * Generates the placeholder tiles served in place of suppressed raster preview
 * tiles, light and dark. Every value is measured off live Google Maps, per
 * pixel, so the interlude is indistinguishable from Maps' own loading states.
 *
 * Light: the styled placeholder Maps paints for unloaded areas (captured by
 * loading normally, then delaying tile data and panning into fresh territory):
 *
 *   background       rgb(242,239,233)
 *   minor lines      rgb(244,242,237), 2px, every 16px
 *   major lines      rgb(246,244,240), 3px, every 128px
 *
 * Note the polarity: the lines are LIGHTER than the ground, a faint white
 * grid on Maps' beige. An earlier version drew darker-than-ground lines and
 * was visibly wrong.
 *
 * Dark: the unstyled boot scaffold (captured by delaying all tile traffic on
 * a cold load; identical under forced light and dark color schemes):
 *
 *   background       rgb(0,0,0)
 *   minor lines      rgb(51,51,51), 1px, every 16px
 *   major lines      rgb(102,102,102), 2px, every 128px
 *
 * 16 and 128 divide 256, so the patterns tile seamlessly across tile seams.
 * Output: src/extension/loading-tile.ts (checked in; rerun after edits here).
 */
import { deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';

const SIZE = 256;
const PALETTES = {
  light: {
    BG: [242, 239, 233], MINOR: [244, 242, 237], MAJOR: [246, 244, 240],
    MINOR_W: 2, MAJOR_W: 3, // measured styled placeholder
  },
  dark: {
    BG: [0, 0, 0], MINOR: [51, 51, 51], MAJOR: [102, 102, 102],
    MINOR_W: 1, MAJOR_W: 2, // measured boot scaffold
  },
};

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

function renderTile({ BG, MINOR, MAJOR, MINOR_W, MAJOR_W }) {
  const colorAt = (x, y) => {
    if (x % 128 < MAJOR_W || y % 128 < MAJOR_W) return MAJOR;
    if (x % 16 < MINOR_W || y % 16 < MINOR_W) return MINOR;
    return BG;
  };
  const raw = Buffer.alloc(SIZE * (SIZE * 3 + 1));
  for (let y = 0; y < SIZE; y++) {
    const rowStart = y * (SIZE * 3 + 1);
    raw[rowStart] = 0; // no filter
    for (let x = 0; x < SIZE; x++) {
      const [r, g, b] = colorAt(x, y);
      const i = rowStart + 1 + x * 3;
      raw[i] = r; raw[i + 1] = g; raw[i + 2] = b;
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(SIZE, 0);
  ihdr.writeUInt32BE(SIZE, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 2;  // RGB
  const png = Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
  return 'data:image/png;base64,' + png.toString('base64');
}
const lightUri = renderTile(PALETTES.light);
const darkUri = renderTile(PALETTES.dark);
writeFileSync('src/extension/loading-tile.ts', `/**
 * Generated by tools/make-loading-tile.mjs. Do not edit by hand; rerun the
 * generator after changing its colors or geometry.
 *
 * 256x256 opaque loading-grid tiles, light and dark, every value measured off
 * live Google Maps (light: the styled unloaded-area placeholder, faint white
 * grid on beige; dark: the unstyled boot scaffold). The runtime picks per
 * Maps' own theme.
 */
export const LOADING_TILE_LIGHT =
  '${lightUri}';

export const LOADING_TILE_DARK =
  '${darkUri}';
`);
console.log('loading tiles written -> src/extension/loading-tile.ts');
