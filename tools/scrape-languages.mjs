/**
 * Regenerates src/extension/options/languages.ts from Google Maps' own
 * Language menu (hamburger menu -> Language), so the options page offers
 * exactly the languages Maps supports, under the names Maps itself uses.
 * Needs a Chrome for Testing build (see tools/browser.mjs) and talks to
 * Google; run it manually when the list needs a refresh.
 */
import { loadPlaywright, findChromeForTesting } from './browser.mjs';
import { mkdtempSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { tmpdir } from 'node:os';

const { chromium } = loadPlaywright();
const ctx = await chromium.launchPersistentContext(mkdtempSync(path.join(tmpdir(), 'gz-langs-')), {
  executablePath: findChromeForTesting(), headless: false, viewport: { width: 1280, height: 900 },
});
try {
  const page = ctx.pages()[0] ?? (await ctx.newPage());
  await page.goto('https://www.google.com/maps/@38.5,-98.0,7z?hl=en&gl=US', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.waitForTimeout(8000);
  await page.click('button[aria-label="Menu"]', { timeout: 10000 });
  await page.waitForTimeout(1500);
  await page.getByText('Language', { exact: false }).first().click({ timeout: 10000 });
  await page.waitForTimeout(2000);
  const langs = await page.evaluate(() => {
    const out = [];
    const seen = new Set();
    for (const el of document.querySelectorAll('a[href*="hl="]')) {
      const text = (el.textContent || '').trim();
      if (!text || text.length > 60) continue;
      const href = el.getAttribute('href');
      if (!href) continue;
      // Language-menu entries link back into /maps on the same origin; the
      // hl-carrying junk (Sign in -> accounts.google.com, help links ->
      // support.google.com) does not.
      let url;
      try { url = new URL(href, location.href); } catch { continue; }
      // A language-switcher link is the CURRENT page with only hl changed;
      // menu items like "Your timeline" link to other /maps paths.
      if (url.origin !== location.origin || url.pathname !== location.pathname) continue;
      const m = /[?&]hl=([A-Za-z-]+)/.exec(url.search);
      if (!m) continue;
      const code = m[1];
      if (!seen.has(code)) { seen.add(code); out.push([code, text]); }
    }
    return out;
  });
  if (langs.length < 40) throw new Error(`only ${langs.length} languages found; Maps menu layout may have changed`);
  // The menu shows the CURRENT language as selected text, not a link, so it
  // never scrapes. The page was loaded with hl=en; put English back, in order.
  if (!langs.some(([code]) => code === 'en')) {
    let at = langs.findIndex(([, name]) => name.localeCompare('English', 'en', { sensitivity: 'base' }) > 0);
    if (at === -1) at = langs.length;
    langs.splice(at, 0, ['en', 'English']);
  }
  // Strip the Unicode bidi isolate marks Google wraps native names in.
  const cleaned = langs.map(([code, name]) => [code, name.replace(/[‪‬‎‏]/g, '').trim()]);
  const body = cleaned.map(([code, name]) => `  [${JSON.stringify(code)}, ${JSON.stringify(name)}],`).join('\n');
  writeFileSync('src/extension/options/languages.ts', `/**
 * Generated by tools/scrape-languages.mjs from Google Maps' own Language menu
 * (${cleaned.length} languages, native names, Maps' menu order). Do not edit by
 * hand; rerun the scraper to refresh.
 */
export const LANGUAGES: readonly (readonly [string, string])[] = [
${body}
];
`);
  console.log(`languages.ts written: ${cleaned.length} languages`);
} finally {
  await ctx.close();
}
